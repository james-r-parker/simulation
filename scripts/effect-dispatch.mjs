#!/usr/bin/env node
// Generates js/sim/effect-dispatch.js from `EFFECTS` in js/sim/effect-list.js (docs/designs/status-effects.md, Phase 5):
// `levelOfEffect`, a `switch` on the effect index that calls each level reader directly, so the compiler sees one call
// target per case and inlines the small readers, where `rule.read` was one call site seeing every reader. A stored
// effect's level is its row, read in place. The list is the source; never hand-edit the module.
//
// Usage:
//   node scripts/effect-dispatch.mjs            # print the module to stdout
//   node scripts/effect-dispatch.mjs --write    # (re)write js/sim/effect-dispatch.js
//   node scripts/effect-dispatch.mjs --check    # exit 1 if the committed module differs from the list
import { fileURLToPath } from 'node:url';
import { EFFECTS } from '../js/sim/effect-list.js';
import { runGeneratedDoc } from './lib/generated-doc.mjs';

const MODULE_PATH = fileURLToPath(new URL('../js/sim/effect-dispatch.js', import.meta.url));

/** The cases a part holds: a `switch` of more would pass the lint's complexity bar of 10. */
export const CASES_PER_PART = 9;

/**
 * @param {readonly import('../js/sim/effects.js').Effect[]} list the effects
 * @returns {string[][]} each effect's case body, in list order
 */
function caseBodies(list) {
    let row = 0;
    return list.map((effect) => {
        if (effect.level === 'stacks') {
            return [`LEVEL[0] = world.effectStacks[${row++}][slot];`];
        }
        const name = /** @type {Function} */ (effect.read).name;
        return effect.level === 'share'
            ? [`${name}(world, slot);`, 'LEVEL[0] = SHARE[0];']
            : [`LEVEL[0] = ${name}(world, slot);`];
    });
}

/**
 * @param {readonly import('../js/sim/effects.js').Effect[]} list the effects
 * @param {number} part the part's index
 * @returns {string[]} the part's function
 */
function renderPart(list, part) {
    const bodies = caseBodies(list);
    const first = part * CASES_PER_PART;
    const last = Math.min(list.length, first + CASES_PER_PART);
    const lines = [
        '/**',
        ` * Leaves in \`LEVEL[0]\` the level of an effect from ${first} to ${last - 1}.`,
        ' * @param {any} world the world',
        ' * @param {number} slot the agent slot',
        " * @param {number} effect the effect's index",
        ' * @returns {void}',
        ' */',
        `function part${part}(world, slot, effect) {`,
        '    switch (effect) {',
    ];
    // `levelOfEffect` sends a part only the effects of its range, so a part's last effect is its `default` (a case that
    // could never miss would be an untaken branch); the last part's default refuses an index past the list.
    const final = last === list.length;
    const caseEnd = final ? last : last - 1;
    for (let e = first; e < caseEnd; e++) {
        lines.push(
            `        case ${e}: // ${list[e].name}`,
            ...bodies[e].map((line) => `            ${line}`),
            '            return;',
        );
    }
    const fallback = final
        ? ['            throw new Error(`levelOfEffect: no effect ${effect}`);']
        : bodies[last - 1].map((line) => `            ${line}`);
    lines.push(
        final ? '        default:' : `        default: // ${last - 1}, ${list[last - 1].name}`,
        ...fallback,
        ...(final ? [] : ['            return;']),
        '    }',
        '}',
        '',
    );
    return lines;
}

/**
 * @param {readonly import('../js/sim/effects.js').Effect[]} [list] the effects (`EFFECTS` by default)
 * @returns {string} the source of js/sim/effect-dispatch.js
 */
export function renderDispatch(list = EFFECTS) {
    const parts = Math.ceil(list.length / CASES_PER_PART);
    const readers = [
        ...new Set(list.filter((e) => e.level !== 'stacks').map((e) => /** @type {Function} */ (e.read).name)),
    ];
    const out = [
        '// Generated by `node scripts/effect-dispatch.mjs --write` from `EFFECTS` in js/sim/effect-list.js - do not hand-edit.',
        "// `levelOfEffect` leaves an effect's level in `LEVEL[0]`: each case calls its reader directly (a stored effect reads its",
        '// row), so the compiler inlines the small readers. A `switch` holds at most nine cases, so the effects are split in parts.',
        '',
        "import { LEVEL, SHARE } from './effect-refs.js';",
        'import {',
        ...readers.sort().map((name) => `    ${name},`),
        "} from './effect-levels.js';",
        '',
    ];
    for (let part = 0; part < parts; part++) {
        out.push(...renderPart(list, part));
    }
    out.push(
        '/**',
        " * Leaves in `LEVEL[0]` an effect's level for the slot: the stored count of a `stacks` effect, else what its reader",
        ' * computes from the body.',
        ' * @param {any} world the world',
        ' * @param {number} slot the agent slot',
        " * @param {number} effect the effect's index in `EFFECTS`",
        ' * @returns {void}',
        ' */',
        'export function levelOfEffect(world, slot, effect) {',
    );
    for (let part = 0; part < parts - 1; part++) {
        out.push(
            `    if (effect < ${(part + 1) * CASES_PER_PART}) {`,
            `        part${part}(world, slot, effect);`,
            '        return;',
            '    }',
        );
    }
    out.push(`    part${parts - 1}(world, slot, effect);`, '}', '');
    return out.join('\n');
}

/**
 * @param {string[]} args the command-line arguments
 * @returns {number} the exit code
 */
export function main(args) {
    return runGeneratedDoc(args, {
        path: MODULE_PATH,
        markdown: renderDispatch(),
        file: 'js/sim/effect-dispatch.js',
        command: 'node scripts/effect-dispatch.mjs',
    });
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
    process.exitCode = main(process.argv.slice(2));
}

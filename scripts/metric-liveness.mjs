#!/usr/bin/env node
// Measures per-metric null share and distinct values in an eval report (docs/designs/metric-trust.md, T23).
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { METRICS } from '../js/evo/metric-registry/index.js';
import { meetsLivenessBar } from '../js/evo/metric-registry/status.js';
import { withCurrentNames } from '../js/evo/metric-registry/renames.js';
import { validateReport } from '../js/evo/report.js';
import { createMetricWriterMain, runAsCli } from './lib/metric-writer-cli.mjs';

const OUTPUT = fileURLToPath(new URL('../js/evo/metric-registry/liveness.js', import.meta.url));
const USAGE = 'usage: metric-liveness <report.json> [--write]';

/**
 * @param {Record<string, any>} rawReport an eval report, possibly holding old metric names
 * @param {string} reportPath the repo-relative path to record in the registry
 * @param {Readonly<Record<string, any>>} [metrics] the registry (injectable for tests)
 * @returns {Readonly<Record<string, import('../js/evo/metric-registry/entry.js').Liveness>>} one reading per metric the
 *   report holds, under its current name; a metric registered after the report was run has no reading
 */
export function measureLiveness(rawReport, reportPath, metrics = METRICS) {
    validateReport(rawReport);
    const report = withCurrentNames(rawReport, metrics);
    const extra = Object.keys(report.metrics).filter((name) => !Object.hasOwn(metrics, name));
    if (extra.length > 0) {
        throw new Error(`report holds unregistered metrics: ${extra.slice(0, 5).join(', ')}`);
    }
    /** @type {Record<string, import('../js/evo/metric-registry/entry.js').Liveness>} */
    const readings = {};
    for (const name of Object.keys(report.metrics).sort()) {
        const values = report.metrics[name].values;
        const present = values.filter((/** @type {number | null} */ value) => value !== null);
        readings[name] = {
            nullShare: (values.length - present.length) / values.length,
            distinct: new Set(present).size,
            report: reportPath,
        };
    }
    return Object.freeze(readings);
}

/**
 * @param {Readonly<Record<string, import('../js/evo/metric-registry/entry.js').Liveness>>} readings the readings
 * @returns {string} the generated module source
 */
export function renderLivenessModule(readings) {
    const quote = (/** @type {string} */ value) => `'${value.replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`;
    const body = Object.entries(readings)
        .sort(([a], [b]) => (a < b ? -1 : 1))
        .map(
            ([name, value]) =>
                `    ${quote(name)}: Object.freeze({\n` +
                `        nullShare: ${value.nullShare},\n` +
                `        distinct: ${value.distinct},\n` +
                `        report: ${quote(value.report)},\n` +
                '    }),',
        )
        .join('\n');
    return [
        '// Generated by scripts/metric-liveness.mjs --write. Re-run it with the reference eval report; do not hand-edit.',
        '/* eslint-disable max-lines */',
        '',
        "/** @type {Readonly<Record<string, import('./entry.js').Liveness>>} */",
        `export const LIVENESS = Object.freeze({${body.length > 0 ? `\n${body}\n` : ''}});`,
        '',
    ].join('\n');
}

/**
 * @param {string[]} args command-line arguments
 * @returns {{reportPath: string, write: boolean} | null} the report and whether to update the generated registry map
 */
function parseArgs(args) {
    const paths = args.filter((arg) => arg !== '--write');
    if (args.some((arg) => arg.startsWith('--') && arg !== '--write') || paths.length !== 1) {
        return null;
    }
    return { reportPath: paths[0], write: args.includes('--write') };
}

/**
 * @param {Readonly<Record<string, import('../js/evo/metric-registry/entry.js').Liveness>>} readings the readings
 * @param {(line: string) => void} print the output sink
 * @returns {void}
 */
function printReadings(readings, print) {
    for (const [name, value] of Object.entries(readings)) {
        print(
            `${name} null=${(value.nullShare * 100).toFixed(1)}% distinct=${value.distinct} ${meetsLivenessBar(value) ? 'live' : 'flat'}`,
        );
    }
}

/** @param {{reportPath: string, write: boolean}} parsed arguments @param {{metrics: Readonly<Record<string, any>>, output: string, read?: (path: string) => any, print: (line: string) => void}} io IO */
function applyRead(parsed, { metrics, output, read, print }) {
    const { reportPath, write } = parsed;
    const report = read === undefined ? JSON.parse(readFileSync(reportPath, 'utf8')) : read(reportPath);
    const readings = measureLiveness(report, reportPath, metrics);
    printReadings(readings, print);
    if (write) {
        writeFileSync(output, renderLivenessModule(readings));
        print(`wrote ${output}`);
    }
}

export const main = createMetricWriterMain({ parse: parseArgs, usage: USAGE }, METRICS, OUTPUT, applyRead);

runAsCli(import.meta.url, main);

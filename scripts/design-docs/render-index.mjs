// Reads every design doc in a directory and renders docs/designs/README.md: the build queue, then docs by status.

import { existsSync, readdirSync, readFileSync } from 'node:fs';
import path from 'node:path';
import { KEYWORDS, UNBUILT } from './header.mjs';
import { lintLinks } from './lint-text.mjs';
import { DesignDocError, toLines } from './markdown.mjs';
import { parseDoc } from './parse-doc.mjs';

/** @typedef {import('./parse-doc.mjs').Doc} Doc */

/** Files in docs/designs/ that are machinery, not designs. */
const EXCLUDED = new Set(['README.md', 'STYLE.md']);

/** Index section order: what is real first, what is only intended last. */
const SECTION_ORDER = ['Implemented', 'In progress', 'Proposed', 'Reference', 'Superseded'];

const HEADER = [
    '# Design docs',
    '',
    "Generated by `node scripts/designs-index.mjs --write` from each doc's `**Status:**` line - **do not hand-edit.**",
    'Add or change a status in the doc itself, then re-run. Conventions: [STYLE.md](STYLE.md).',
    '',
];

/**
 * Builds the index Markdown for every doc in a directory.
 * @param {string} designsDir
 * @returns {string}
 */
export const buildIndex = (designsDir) => renderIndex(readDocs(designsDir));

/**
 * Parses and lints every design doc in a directory, sorted by title.
 * @param {string} designsDir
 * @returns {Doc[]}
 */
export function readDocs(designsDir) {
    if (!existsSync(designsDir)) {
        return [];
    }
    return (
        readdirSync(designsDir)
            .filter((name) => name.endsWith('.md') && !EXCLUDED.has(name))
            .map((name) => {
                const body = readFileSync(path.join(designsDir, name), 'utf8');
                lintLinks(designsDir, name, toLines(body));
                return parseDoc(name, body);
            })
            // Code-unit sort: the output has to be identical on every machine and in CI.
            .sort((a, b) => compare(a.title, b.title))
    );
}

/**
 * Renders the index for parsed docs.
 * @param {Doc[]} docs
 * @returns {string}
 */
export function renderIndex(docs) {
    const lines = [...HEADER, ...renderQueue(docs)];
    for (const heading of SECTION_ORDER) {
        lines.push(
            ...renderSection(
                heading,
                docs.filter((d) => d.keyword === heading),
            ),
        );
    }
    if (docs.length === 0) {
        lines.push('No design docs yet. Add one under `docs/designs/` and re-run the generator.', '');
    }
    return lines.join('\n').replace(/\n+$/, '') + '\n';
}

/**
 * The build queue: every unbuilt doc by its `**Priority:**` rank, 1 first. Ranks are unique so the next item is
 * never ambiguous.
 * @param {Doc[]} docs
 * @returns {string[]}
 */
function renderQueue(docs) {
    const queue = docs.filter((d) => d.priority).sort((a, b) => rank(a) - rank(b));
    assertUniqueRanks(queue);
    if (queue.length === 0) {
        return [];
    }
    return [
        `## Build queue (${queue.length})`,
        '',
        "Unbuilt docs in priority order - 1 is built next. Set in each doc's `**Priority:**` line; the evolution loop proposes re-ranks.",
        '',
        ...queue.map((doc) => `${rank(doc)}. [${doc.title}](${doc.fileName}) - ${doc.priority?.reason}`),
        '',
    ];
}

/**
 * @param {Doc[]} queue
 */
function assertUniqueRanks(queue) {
    /** @type {Map<number, string[]>} */
    const byRank = new Map();
    for (const doc of queue) {
        byRank.set(rank(doc), [...(byRank.get(rank(doc)) ?? []), doc.fileName]);
    }
    const clashes = [...byRank].filter(([, names]) => names.length > 1);
    if (clashes.length > 0) {
        const detail = clashes.map(([r, names]) => `${r} is used by ${[...names].sort().join(', ')}`).join('; ');
        throw new DesignDocError(`Priority ranks must be unique: ${detail}`);
    }
}

/**
 * One status section. The stamp and dependencies only matter while a doc is a claim about unwritten code.
 * @param {string} heading
 * @param {Doc[]} group
 * @returns {string[]}
 */
function renderSection(heading, group) {
    if (group.length === 0) {
        return [];
    }
    const blurb = KEYWORDS.find((k) => k.name === heading)?.blurb ?? '';
    const unbuilt = UNBUILT.has(heading);
    return [`## ${heading} (${group.length})`, '', blurb, '', ...group.map((doc) => renderEntry(doc, unbuilt)), ''];
}

/**
 * @param {Doc} doc
 * @param {boolean} unbuilt
 */
function renderEntry(doc, unbuilt) {
    const detail = doc.detail.length > 0 ? ` - ${doc.detail}` : '';
    const stamp = unbuilt && doc.validated ? ` _(validated ${doc.validated.sha}, ${doc.validated.date})_` : '';
    const deps = unbuilt && doc.dependsOn.length > 0 ? ` _(depends on ${doc.dependsOn.join(', ')})_` : '';
    return `- [${doc.title}](${doc.fileName})${detail}${stamp}${deps}`;
}

/** @param {Doc} doc */
const rank = (doc) => doc.priority?.rank ?? 0;

/**
 * @param {string} a
 * @param {string} b
 */
function compare(a, b) {
    if (a === b) {
        return 0;
    }
    return a < b ? -1 : 1;
}

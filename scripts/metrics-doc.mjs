#!/usr/bin/env node
// Generates docs/designs/metrics.md from the metric registry: one row per metric with what it means, its unit, the
// direction `eval:compare` scores, its status, the seeds a verdict needs and the smallest change it detects at 32 seeds
// (docs/designs/metric-trust.md, Generated table). The registry is the source; never hand-edit the doc.
//
// Usage:
//   node scripts/metrics-doc.mjs            # print the doc to stdout
//   node scripts/metrics-doc.mjs --write    # (re)write docs/designs/metrics.md
//   node scripts/metrics-doc.mjs --check    # exit 1 if the committed doc differs from the registry
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { METRICS, minSeedsFor } from '../js/evo/metric-registry/index.js';
import { metricStatus } from '../js/evo/metric-registry/status.js';

const DOC_PATH = fileURLToPath(new URL('../docs/designs/metrics.md', import.meta.url));

/** The heading of each family section, in the order the doc lists them. */
const FAMILIES = Object.freeze([
    ['core', 'Core'],
    ['hunters', 'Hunters'],
    ['intent', 'Intent'],
    ['scenes-ecology', 'Scenes - ecology'],
    ['scenes-social', 'Scenes - social'],
    ['brain', 'Brain'],
    ['world', 'World'],
]);

const HEADER = ['Metric', 'Meaning', 'Unit', 'Better', 'Status', 'Seeds', 'MDE at 32'];

/**
 * @param {string} text a cell's text
 * @returns {string} the text on one line with its pipes escaped
 */
const cell = (text) => text.replace(/\s+/g, ' ').trim().replace(/\|/g, '\\|');

/**
 * @param {string[][]} rows the header row and the body rows, each cell already escaped
 * @returns {string[]} a Markdown table with every column padded to its widest cell, as Prettier writes it
 */
export function renderTable(rows) {
    const widths = rows[0].map((_, col) => Math.max(3, ...rows.map((cells) => cells[col].length)));
    const line = (/** @type {string[]} */ cells) => `| ${cells.map((text, i) => text.padEnd(widths[i])).join(' | ')} |`;
    const rule = `| ${widths.map((width) => '-'.repeat(width)).join(' | ')} |`;
    return [line(rows[0]), rule, ...rows.slice(1).map(line)];
}

/**
 * @param {import('../js/evo/metric-registry/entry.js').MetricEntry} entry a registry entry
 * @returns {string} the smallest detectable change at 32 seeds (`<n> abs` for a share, a percentage of the reference mean
 *   for the rest), `none` when no step is detected, `-` before it is measured
 */
function mdeCell(entry) {
    if (entry.power === null) {
        return '-';
    }
    if (entry.power.mde32 === null) {
        return 'none';
    }
    return entry.unit === 'share'
        ? `${Number(entry.power.mde32.toPrecision(3))} abs`
        : `${(entry.power.mde32 * 100).toFixed(0)}%`;
}

/**
 * @param {string} name a metric name
 * @param {import('../js/evo/metric-registry/entry.js').MetricEntry} entry its entry
 * @returns {string[]} the table row
 */
function row(name, entry) {
    const better = entry.direction === 'watch' ? `watch (${entry.intended ?? 'higher'})` : entry.direction;
    return [
        `\`${name}\``,
        entry.meaning,
        entry.unit,
        better,
        metricStatus(entry),
        String(entry.minSeeds ?? minSeedsFor(name)),
        mdeCell(entry),
    ].map(cell);
}

/**
 * @param {Readonly<Record<string, import('../js/evo/metric-registry/entry.js').MetricEntry>>} [metrics] the registry
 * @returns {string} the Markdown of docs/designs/metrics.md
 */
export function renderMetricsDoc(metrics = METRICS) {
    const entries = Object.entries(metrics).sort(([a], [b]) => (a < b ? -1 : 1));
    const counts = { verified: 0, unverified: 0, deprecated: 0 };
    for (const [, entry] of entries) {
        counts[metricStatus(entry)] += 1;
    }
    const out = [
        '# Metrics',
        '',
        `**Status:** Reference - the ${entries.length} eval metrics of a live report, generated from \`js/evo/metric-registry/\`: ${counts.verified} verified, ${counts.unverified} unverified, ${counts.deprecated} deprecated.`,
        '',
        'Generated by `node scripts/metrics-doc.mjs --write` from the registry - **do not hand-edit.** Change an entry in',
        '`js/evo/metric-registry/`, then re-run. The checks and the registry are described in [metric-trust.md](metric-trust.md);',
        'the metric definitions in full (`counts`, `nullWhen`) are in the registry entries.',
        '',
        '- **Better** is the direction `eval:compare` scores as an improvement. A `watch` metric gets an interval and no',
        '  verdict; the direction in brackets is the one `eval:power --include-watch` plants.',
        '- **Status** is `verified` when the metric has an arithmetic test, a source test, a liveness read and a measured',
        '  power; `unverified` otherwise; `deprecated` when it is kept only until its deletion task. A verdict, a keep',
        '  rule or a screen gate rests only on `verified` metrics.',
        '- **Seeds** is the fewest seeds per arm a verdict needs: the measured `minSeeds`, else the legacy 32 of the four',
        '  noisy metrics, else 16.',
        "- **MDE at 32** is the smallest change the verdict detects at 32 seeds per arm: a percentage of the metric's mean in the",
        '  reference run, or an absolute change (`abs`) for a metric of unit `share`; `-` before it is measured.',
        '',
    ];
    for (const [family, title] of FAMILIES) {
        const rows = entries.filter(([, entry]) => entry.family === family).map(([name, entry]) => row(name, entry));
        out.push(`## ${title}`, '', ...renderTable([HEADER, ...rows]), '');
    }
    return `${out.join('\n').trimEnd()}\n`;
}

/**
 * @param {string[]} args the command-line arguments
 * @param {{ path?: string, metrics?: Readonly<Record<string, import('../js/evo/metric-registry/entry.js').MetricEntry>> }} [options]
 *   the doc's path and the registry
 * @returns {number} the exit code
 */
export function main(args, { path = DOC_PATH, metrics = METRICS } = {}) {
    const unknown = args.filter((arg) => arg !== '--write' && arg !== '--check');
    if (unknown.length > 0) {
        process.stderr.write(`unknown argument: ${unknown.join(' ')} (expected --write or --check)\n`);
        return 2;
    }
    const markdown = renderMetricsDoc(metrics);
    if (args.includes('--check')) {
        const current = existsSync(path) ? readFileSync(path, 'utf8') : '';
        if (current !== markdown) {
            process.stderr.write('docs/designs/metrics.md is stale. Run: node scripts/metrics-doc.mjs --write\n');
            return 1;
        }
        process.stdout.write('docs/designs/metrics.md is up to date.\n');
        return 0;
    }
    if (args.includes('--write')) {
        writeFileSync(path, markdown);
        process.stdout.write('Wrote docs/designs/metrics.md\n');
        return 0;
    }
    process.stdout.write(markdown);
    return 0;
}

if (process.argv[1] && process.argv[1] === fileURLToPath(import.meta.url)) {
    process.exitCode = main(process.argv.slice(2));
}

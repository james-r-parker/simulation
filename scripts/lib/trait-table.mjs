// The trait table (docs/designs/body-genes.md, "The table"): for each spec and each trait whose span is above 0, the value
// of every lane the trait moves, and of every lane its paired cost moves, at the gene's minimum, at 0 and at its maximum.
// The numbers come from `applyTraits` itself on a one-slot stand-in world, so the table cannot drift from the sim.

import { TRAITS, applyTraits } from '../../js/sim/body-traits.js';
import { laneBases } from '../../js/sim/body-lanes.js';
import { TRAIT_SLOTS } from '../../js/sim/brain-layout.js';
import { SPEC_NAMES } from '../../js/sim/specs.js';
import { renderTable } from '../metrics-doc.mjs';

/** A gene far enough out that `tanh` has saturated: the ratio is `1 - span` or `1 + span` exactly. */
const EXTREME_GENE = 50;

/**
 * @typedef {object} TraitRow one lane a trait moves in one spec
 * @property {string} trait the trait's name
 * @property {number} span the spec's span for it
 * @property {string} lane the lane's name, `(cost)` after it for a paired cost lane
 * @property {number[]} values the lane at the gene's minimum, 0 and maximum
 */

/**
 * @param {Readonly<Record<string, any>>} config the validated config
 * @param {number} spec the spec index
 * @param {{trait: Readonly<import('../../js/sim/body-traits.js').Trait>, gene: number}} setting the trait and its gene
 * @returns {Record<string, number>} every lane of a body of that spec whose only non-neutral trait is `trait` at `gene`
 */
function lanesAt(config, spec, { trait, gene }) {
    const bases = laneBases(config, SPEC_NAMES[spec]);
    const lanes = Object.fromEntries(Object.entries(bases).map(([name, value]) => [name, Float64Array.of(value)]));
    const weights = new Float64Array(TRAIT_SLOTS);
    weights[trait.index] = gene;
    const traitSpans = new Float64Array((spec + 1) * TRAIT_SLOTS);
    traitSpans[spec * TRAIT_SLOTS + trait.index] = config.specialisations[SPEC_NAMES[spec]].genes[trait.name];
    const world = {
        lanes,
        config,
        layout: { weightCount: TRAIT_SLOTS, traitStart: 0 },
        weights,
        traitSpans,
        spec: [spec],
    };
    applyTraits(world, 0, [trait]);
    return Object.fromEntries(Object.entries(lanes).map(([name, array]) => [name, array[0]]));
}

/**
 * @param {Readonly<Record<string, any>>} config the validated config
 * @param {string} specName a specialisation name
 * @param {readonly Readonly<import('../../js/sim/body-traits.js').Trait>[]} [traits] the registry (a parameter for tests)
 * @returns {TraitRow[]} a row for every lane moved by a trait the spec varies (span above 0), in registry order, the
 *   effect lanes then the cost lanes; a `raw` trait has no lane and is left out
 */
export function traitRows(config, specName, traits = TRAITS) {
    const spec = SPEC_NAMES.indexOf(specName);
    /** @type {TraitRow[]} */
    const rows = [];
    for (const trait of traits) {
        const span = config.specialisations[specName].genes[trait.name];
        if (span === 0 || trait.kind === 'raw') {
            continue;
        }
        const at = [-EXTREME_GENE, 0, EXTREME_GENE].map((gene) => lanesAt(config, spec, { trait, gene }));
        const lanes = [
            ...trait.effects.map((effect) => effect.lane),
            ...trait.costs.map((cost) => `${cost.lane} (cost)`),
        ];
        for (const lane of lanes) {
            const name = lane.replace(' (cost)', '');
            rows.push({ trait: trait.name, span, lane, values: at.map((lanes0) => lanes0[name]) });
        }
    }
    return rows;
}

/**
 * @param {number} value a lane's value
 * @returns {string} the value to four significant figures
 */
const format = (value) => String(Number(value.toPrecision(4)));

/**
 * @param {Readonly<Record<string, any>>} config the validated config
 * @returns {string} the Markdown of `docs/trait-table.md`
 */
export function renderTraitTable(config) {
    const out = [
        '# Trait table',
        '',
        'Generated by `node scripts/traits.mjs --write` (`npm run traits -- --write`) from the trait registry',
        '(`js/sim/body-traits.js`) and the default config - **do not hand-edit.** For each spec, every trait it varies',
        '(span above 0) and each lane the trait, or its paired cost, moves, at the gene minimum, at 0 and at the maximum.',
        'The values are what `applyTraits` writes. A trait the spec does not vary, and the `raw` trait `learn`, have no',
        'row. `npm run traits` with `--config` or `--set` prints the table for another config.',
        '',
    ];
    for (const specName of SPEC_NAMES) {
        const rows = traitRows(config, specName).map((row) => [
            `\`${row.trait}\``,
            String(row.span),
            `\`${row.lane}\``,
            ...row.values.map(format),
        ]);
        out.push(`## ${specName}`, '');
        out.push(
            ...(rows.length === 0
                ? ['No trait varies.']
                : renderTable([['Trait', 'Span', 'Lane', 'Min', '0', 'Max'], ...rows])),
        );
        out.push('');
    }
    return `${out.join('\n').trimEnd()}\n`;
}

#!/usr/bin/env node
// Applies eval:power JSON to the registry (docs/designs/metric-trust.md, T26).
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { METRICS } from '../js/evo/metric-registry/index.js';
import { minSeedsFromPower } from '../js/evo/metric-registry/status.js';
import { withCurrentNames } from '../js/evo/metric-registry/renames.js';
import { validateReport } from '../js/evo/report.js';

const OUTPUT = fileURLToPath(new URL('../js/evo/metric-registry/power.js', import.meta.url));
const USAGE = 'usage: metric-power-write <power.json> --report <eval-report.json> [--write]';

function checkRows(rows, metrics) {
    if (!Array.isArray(rows)) {
        throw new Error('power JSON must contain rows');
    }
    const unknown = [...new Set(rows.map((row) => row.metric).filter((name) => !Object.hasOwn(metrics, name)))];
    if (unknown.length > 0) {
        throw new Error(`power JSON holds unregistered metrics: ${unknown.slice(0, 5).join(', ')}`);
    }
    return rows;
}

function setReading(grouped, row, report, reportPath) {
    if (![16, 32].includes(row.size)) {
        return;
    }
    const metric = row.metric;
    const current = Object.hasOwn(report.metrics, metric) ? report.metrics[metric] : null;
    if (current === null) {
        throw new Error(`source report lacks metric ${metric}`);
    }
    const value = (grouped[metric] ??= {
        fpr16: null,
        fpr32: null,
        mde16: null,
        mde32: null,
        referenceMean: current.mean ?? 0,
        report: reportPath,
    });
    value[`fpr${row.size}`] = row.falsePositive;
    value[`mde${row.size}`] = row.detectable;
}

/** @param {string} source command output @returns {Record<string, any>} parsed JSON object */
export function parseJsonOutput(source) {
    const jsonStart = source.indexOf('{');
    if (jsonStart < 0) {
        throw new Error('no JSON object in command output');
    }
    return JSON.parse(source.slice(jsonStart));
}

/** @param {string} path file path @returns {Record<string, any>} parsed JSON object */
function readJson(path) {
    return parseJsonOutput(readFileSync(path, 'utf8'));
}

/**
 * @param {Record<string, any>} rawPower eval:power JSON
 * @param {Record<string, any>} rawReport the source eval report
 * @param {string} reportPath repo-relative source report path
 * @param {Readonly<Record<string, any>>} metrics registry
 * @returns {Readonly<Record<string, import('../js/evo/metric-registry/entry.js').Power>>} readings
 */
export function readPower(rawPower, rawReport, reportPath, metrics = METRICS) {
    validateReport(rawReport);
    const report = withCurrentNames(rawReport, metrics);
    const rows = checkRows(rawPower?.rows, metrics);
    /** @type {Record<string, Record<string, any>>} */
    const grouped = {};
    for (const row of rows) {
        setReading(grouped, row, report, reportPath);
    }
    return Object.freeze(grouped);
}

/** @param {Readonly<Record<string, import('../js/evo/metric-registry/entry.js').Power>>} readings readings */
export function renderPowerModule(readings) {
    const quote = (/** @type {string} */ value) => `'${value.replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`;
    const body = Object.entries(readings)
        .sort(([a], [b]) => a.localeCompare(b))
        .map(
            ([name, value]) =>
                `    ${quote(name)}: Object.freeze({\n` +
                `        fpr16: ${value.fpr16},\n        fpr32: ${value.fpr32},\n` +
                `        mde16: ${value.mde16},\n        mde32: ${value.mde32},\n` +
                `        referenceMean: ${value.referenceMean},\n        report: ${quote(value.report)},\n` +
                '    }),',
        )
        .join('\n');
    return [
        '// Generated by scripts/metric-power-write.mjs --write. Re-run it with the reference eval:power JSON; do not hand-edit.',
        '/* eslint-disable max-lines */',
        '',
        "/** @type {Readonly<Record<string, import('./entry.js').Power>>} */",
        `export const POWER = Object.freeze({${body ? `\n${body}\n` : ''}});`,
        '',
    ].join('\n');
}

/** @param {string[]} args CLI args */
function parseArgs(args) {
    const reportIndex = args.indexOf('--report');
    const powerPath = args.find((arg) => !arg.startsWith('--') && args[args.indexOf(arg) - 1] !== '--report');
    if (
        powerPath === undefined ||
        reportIndex < 0 ||
        args[reportIndex + 1] === undefined ||
        args.some((arg) => arg.startsWith('--') && !['--report', '--write'].includes(arg))
    ) {
        process.stderr.write(`${USAGE}\n`);
        return null;
    }
    return { powerPath, reportPath: args[reportIndex + 1], write: args.includes('--write') };
}

function applyRead(parsed, { metrics, output, read, print }) {
    const load = read ?? readJson;
    const { powerPath, reportPath, write } = parsed;
    const readings = readPower(load(powerPath), load(reportPath), reportPath, metrics);
    for (const [name, power] of Object.entries(readings)) {
        const minimum = minSeedsFromPower({ unit: metrics[name].unit, power });
        print(`${name} minSeeds=${minimum ?? 'null'}`);
    }
    if (write) {
        writeFileSync(output, renderPowerModule(readings));
        print(`wrote ${output}`);
    }
}

/** @param {string[]} args CLI args @param {{metrics?: Readonly<Record<string, any>>, output?: string, read?: (path: string) => any, print?: (line: string) => void}} [io] IO */
export function main(
    args,
    { metrics = METRICS, output = OUTPUT, read, print = (line) => process.stdout.write(`${line}\n`) } = {},
) {
    const parsed = parseArgs(args);
    if (parsed === null) {
        process.stderr.write(`${USAGE}\n`);
        return 2;
    }
    try {
        applyRead(parsed, { metrics, output, read, print });
        return 0;
    } catch (error) {
        process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`);
        return 1;
    }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
    process.exitCode = main(process.argv.slice(2));
}

#!/usr/bin/env node
// Generates docs/config-keys.md from the config's defaults and rules: one row per key with its default and the rule
// that validates it (docs/designs/registries.md, Per-slot state and config). Config stays two maps that exact-key
// validation keeps in step; this table is how to read them side by side. Never hand-edit the doc.
//
// Usage:
//   node scripts/config-doc.mjs            # print the doc to stdout
//   node scripts/config-doc.mjs --write    # (re)write docs/config-keys.md
//   node scripts/config-doc.mjs --check    # exit 1 if the committed doc differs from the config
import { fileURLToPath } from 'node:url';
import { DEFAULTS } from '../js/sim/config-defaults.js';
import { CONFIG_RULES } from '../js/sim/config-validate.js';
import { runGeneratedDoc } from './lib/generated-doc.mjs';
import { renderTable } from './metrics-doc.mjs';

const DOC_PATH = fileURLToPath(new URL('../docs/config-keys.md', import.meta.url));

/**
 * @param {string} text a cell's text
 * @returns {string} the text on one line with its pipes escaped
 */
const cell = (text) => text.replace(/\s+/g, ' ').trim().replace(/\|/g, '\\|');

/**
 * @param {unknown} value a default
 * @returns {string} the default as a cell: a number or a boolean as written, a group as its key count
 */
function defaultCell(value) {
    if (Array.isArray(value)) {
        return `[${value.length} items]`;
    }
    if (value !== null && typeof value === 'object') {
        return `{${Object.keys(value).length} keys}`;
    }
    return String(value);
}

/**
 * @param {import('../js/sim/config-rules.js').Rule} rule a key's rule
 * @returns {string} the rule as a cell: its type and bounds
 */
function ruleCell(rule) {
    if (rule.type === 'enum') {
        return `one of ${(rule.values ?? []).join(', ')}`;
    }
    const bounds = [
        rule.min !== undefined && rule.min !== -Infinity ? `>= ${rule.min}` : '',
        rule.gt === undefined ? '' : `> ${rule.gt}`,
        rule.max !== undefined && rule.max !== Infinity ? `<= ${rule.max}` : '',
        rule.lt === undefined ? '' : `< ${rule.lt}`,
        rule.infinite ? 'or Infinity' : '',
    ].filter(Boolean);
    return [rule.type, ...bounds].join(' ');
}

/** @returns {string} the Markdown of docs/config-keys.md */
export function renderConfigDoc() {
    const keys = Object.keys(DEFAULTS).sort();
    const rows = keys.map((key) => [
        `\`${key}\``,
        cell(defaultCell(DEFAULTS[key])),
        cell(CONFIG_RULES[key] === undefined ? 'no rule' : ruleCell(CONFIG_RULES[key])),
    ]);
    const out = [
        '# Config keys',
        '',
        `Generated by \`node scripts/config-doc.mjs --write\` from \`DEFAULTS\` in \`js/sim/config-defaults.js\` and the rules in`,
        '`js/sim/config-validate.js` - **do not hand-edit.** A key is a default and a rule; exact-key validation fails a key',
        `with one and not the other when the world starts. ${keys.length} keys.`,
        '',
        ...renderTable([['Key', 'Default', 'Rule'], ...rows]),
    ];
    return `${out.join('\n')}\n`;
}

/**
 * @param {string[]} args the command-line arguments
 * @param {{ path?: string }} [options] the doc's path
 * @returns {number} the exit code
 */
export function main(args, { path = DOC_PATH } = {}) {
    return runGeneratedDoc(args, {
        path,
        markdown: renderConfigDoc(),
        file: 'docs/config-keys.md',
        command: 'node scripts/config-doc.mjs',
    });
}

if (process.argv[1] && process.argv[1] === fileURLToPath(import.meta.url)) {
    process.exitCode = main(process.argv.slice(2));
}

#!/usr/bin/env node
// Generates docs/log-events.md from `EVENTS` in js/sim/events.js: one row per event with its code, the log event it
// becomes, its level and the named fields of its record, plus the cause lists (docs/designs/registries.md, Events).
// The registry is the source; never hand-edit the doc.
//
// Usage:
//   node scripts/events-doc.mjs            # print the doc to stdout
//   node scripts/events-doc.mjs --write    # (re)write docs/log-events.md
//   node scripts/events-doc.mjs --check    # exit 1 if the committed doc differs from the registry
import { fileURLToPath } from 'node:url';
import { BORN_CAUSES, DEATH_CAUSES, EVENT_FIELDS_AT, EVENTS } from '../js/sim/events.js';
import { runGeneratedDoc } from './lib/generated-doc.mjs';
import { renderTable } from './metrics-doc.mjs';

const DOC_PATH = fileURLToPath(new URL('../docs/log-events.md', import.meta.url));

/**
 * @param {import('../js/sim/events.js').EventDef} def an event
 * @returns {string[]} its table row
 */
function eventRow(def) {
    const fields = def.fields.map((field, i) => `${EVENT_FIELDS_AT + i} ${field}`);
    return [
        String(def.code),
        `\`${def.name}\``,
        def.log === null ? 'none (unused)' : `\`${def.log}\``,
        def.level,
        fields.length === 0 ? '-' : fields.join(', '),
    ];
}

/**
 * @param {readonly import('../js/sim/events.js').Cause[]} causes a cause list
 * @returns {string[]} its table
 */
function causeTable(causes) {
    const rows = causes.map((cause) => [String(cause.code), `\`${cause.key}\``, cause.name, cause.colour]);
    return renderTable([['Code', 'Key', 'Log name', 'Colour'], ...rows]);
}

/** @returns {string} the Markdown of docs/log-events.md */
export function renderEventsDoc() {
    const out = [
        '# Log events',
        '',
        'Generated by `node scripts/events-doc.mjs --write` from `EVENTS` in `js/sim/events.js` - **do not hand-edit.** Add an',
        'event, or a field, there and re-run; `drainEvents` in `js/sim/log.js` writes every record from it, and how a field is',
        'decoded in the log (cause names, flags, a packed word) is in `js/sim/log-rules.js`.',
        '',
        'A record is 13 numbers: offset 0 is the type, offset 1 the tick, and the named fields follow from offset 2',
        '(`EVENT.AGENT_DIED.CAUSE` is the offset of the cause). A field the log leaves out (`sex`, `size`, a herd centroid) is',
        'still in the record for the observer and the effects.',
        '',
        '## Events',
        '',
        ...renderTable([['Code', 'Event', 'Log event', 'Level', 'Fields (offset name)'], ...EVENTS.map(eventRow)]),
        '',
        '## Birth causes',
        '',
        ...causeTable(BORN_CAUSES),
        '',
        '## Death causes',
        '',
        ...causeTable(DEATH_CAUSES),
    ];
    return `${out.join('\n')}\n`;
}

/**
 * @param {string[]} args the command-line arguments
 * @param {{ path?: string }} [options] the doc's path
 * @returns {number} the exit code
 */
export function main(args, { path = DOC_PATH } = {}) {
    return runGeneratedDoc(args, {
        path,
        markdown: renderEventsDoc(),
        file: 'docs/log-events.md',
        command: 'node scripts/events-doc.mjs',
    });
}

if (process.argv[1] && process.argv[1] === fileURLToPath(import.meta.url)) {
    process.exitCode = main(process.argv.slice(2));
}
